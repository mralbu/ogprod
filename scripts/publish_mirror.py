"""Publish canonical Layer-1 Parquet & GeoParquet files to the Hugging Face v2 mirror.

Usable both locally (with ``HF_TOKEN``) and in GitHub Actions (with ``secrets.HF_TOKEN``):

    uv run --group publish python scripts/publish_mirror.py --data-dir ./data

Features:
- Computes SHA-256, byte size, row counts, period spans, and rate sums per partition.
- Skips unchanged files whose ``(bytes, sha256)`` already match the remote manifest.
- Enforces sanity gates (>15% production row/rate drop, >10% geo row drop, empty files).
- Merges changed entries into remote ``manifest.json`` without deleting untouched partitions.
- Supports ``--prune-legacy`` for the one-time v1 -> v2 cutover (deletes legacy files & resets).
- Pushes atomically via ``HfApi.create_commit(..., parent_commit=...)`` and emits
  ``changed=true|false`` to ``$GITHUB_OUTPUT`` when running in GitHub Actions.
"""

from __future__ import annotations

import argparse
import importlib
import json
import os
import sys
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from ogprod import mirror, schema, sources, store

_PRESERVED_ROOT_FILES = frozenset({".gitattributes", "README.md", "manifest.json"})

_DATASET_README = """\
---
license: mit
task_categories:
  - tabular-regression
pretty_name: ogprod — Public Oil & Gas Production and Geospatial Dataset (v2)
tags:
  - oil-and-gas
  - energy
  - production
  - geoparquet
  - parquet
---

# ogprod (v2 Mirror)

Pre-normalized public monthly oil & gas production, injection, and geospatial tables
generated by [`ogprod`](https://github.com/mralbu/ogprod).

## Canonical Units (`schema_version: 2`)

All production and injection rates are calendar-day averages stored as `float32` ZSTD
Parquet (`row_group_size=128_000`):

- **Liquids** (`oil_prod`, `condensate_prod`, `ngl_prod`, `water_prod`, `water_inj`): **`bbl/d`**
- **Gases** (`gas_prod`, `gas_inj`, `co2_inj`): **`e3m3/d`** (`10³ m³/d`, thousand m³/day)

## Layout

- `manifest.json` — v2 index with SHA-256 checksums, byte sizes, row counts, and period bounds
- `production/source=<source>/year=<yyyy>/data.parquet` — wide monthly rates
- `geo/fields/<source>.parquet` — GeoParquet 1.1 field polygons (`EPSG:4326` + `bbox`)
- `geo/facilities/<source>.parquet` — GeoParquet 1.1 platforms / FPSOs (`EPSG:4326` + `bbox`)
- `geo/wells/<source>.parquet` — GeoParquet 1.1 wells (`EPSG:4326` + `bbox`)

## Usage

```sh
ogprod ingest brazil --year 2026
ogprod ingest norway
ogprod ingest mexico
```
"""


class SanityGateError(RuntimeError):
    """Raised when one or more sanity-gate checks fail before publishing."""


@dataclass(frozen=True)
class PublishPlan:
    """Computed diff between the local Layer-1 store and the remote HF dataset."""

    uploads: tuple[tuple[str, Path], ...]
    skipped: tuple[str, ...]
    deletes: tuple[str, ...]
    merged_manifest: dict[str, Any]
    write_readme: bool

    @property
    def changed(self) -> bool:
        return bool(self.uploads or self.deletes)


@dataclass(frozen=True)
class PublishResult:
    """Outcome of a publish run."""

    repo_id: str
    changed: bool
    uploaded: int
    skipped: int
    deleted: int
    commit_url: str | None = None
    dry_run: bool = False


def _load_hf_hub() -> Any:
    try:
        return importlib.import_module("huggingface_hub")
    except ModuleNotFoundError as err:
        raise RuntimeError(
            "huggingface-hub is required to publish; run with 'uv run --group publish ...'"
        ) from err


def _source_metadata(source_name: str, updated_at: str) -> dict[str, Any]:
    meta: dict[str, Any] = {"production": {}, "geo": {}, "updated_at": updated_at}
    if source_name in sources.available():
        conn = sources.get(source_name)
        meta["country"] = conn.country
        meta["country_code"] = conn.country_code
        meta["publisher"] = conn.publisher
        meta["docs_url"] = conn.docs_url
        meta["entity_type"] = conn.entity_type.value
    return meta


def scan_local_store(
    store_root: Path,
    *,
    source_filter: set[str] | None = None,
    updated_at: str | None = None,
) -> dict[str, Any]:
    """Scan local Layer-1 ``store/`` files and compute v2 manifest entries."""
    ts = updated_at or datetime.now(tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    result: dict[str, Any] = {}

    prod_root = store_root / "production"
    if prod_root.exists():
        for src_dir in sorted(prod_root.glob("source=*")):
            src_name = src_dir.name.split("=", 1)[1]
            if source_filter is not None and src_name not in source_filter:
                continue
            for yr_dir in sorted(src_dir.glob("year=*")):
                data_file = yr_dir / "data.parquet"
                if not data_file.exists():
                    continue
                year_str = yr_dir.name.split("=", 1)[1]
                rel = f"production/source={src_name}/year={year_str}/data.parquet"
                src_entry = result.setdefault(src_name, _source_metadata(src_name, ts))
                src_entry["production"][year_str] = mirror.compute_partition_stats(
                    data_file, rel, updated_at=ts
                )

    _scan_local_geo(store_root, result, source_filter=source_filter, updated_at=ts)
    return result


def _scan_local_geo(
    store_root: Path,
    result: dict[str, Any],
    *,
    source_filter: set[str] | None,
    updated_at: str,
) -> None:
    geo_root = store_root / "geo"
    if not geo_root.exists():
        return
    for kind in schema.GeoKind:
        kind_dir = geo_root / kind.value
        if not kind_dir.exists():
            continue
        for parquet_path in sorted(kind_dir.glob("*.parquet")):
            src_name = parquet_path.stem
            if source_filter is not None and src_name not in source_filter:
                continue
            rel = f"geo/{kind.value}/{src_name}.parquet"
            src_entry = result.setdefault(src_name, _source_metadata(src_name, updated_at))
            src_entry["geo"][kind.value] = mirror.compute_geo_stats(
                parquet_path, rel, updated_at=updated_at
            )


def _remote_entry_map(remote_manifest: dict[str, Any] | None) -> dict[str, dict[str, Any]]:
    if not remote_manifest or remote_manifest.get("schema_version") != 2:
        return {}
    entries: dict[str, dict[str, Any]] = {}
    for src_data in remote_manifest.get("sources", {}).values():
        for entry in src_data.get("production", {}).values():
            entries[str(entry["path"])] = entry
        for entry in src_data.get("geo", {}).values():
            entries[str(entry["path"])] = entry
    return entries


def _manifest_paths(manifest: dict[str, Any]) -> set[str]:
    paths: set[str] = set()
    for src_data in manifest.get("sources", {}).values():
        for entry in src_data.get("production", {}).values():
            paths.add(str(entry["path"]))
        for entry in src_data.get("geo", {}).values():
            paths.add(str(entry["path"]))
    return paths


def _diff_local_uploads(
    store_root: Path,
    local_sources: dict[str, Any],
    remote_entries: dict[str, dict[str, Any]],
) -> tuple[list[tuple[str, Path]], list[str]]:
    uploads: list[tuple[str, Path]] = []
    skipped: list[str] = []
    for src_data in local_sources.values():
        all_entries = [
            *src_data.get("production", {}).values(),
            *src_data.get("geo", {}).values(),
        ]
        for entry in all_entries:
            rel = str(entry["path"])
            old = remote_entries.get(rel)
            if (
                old is not None
                and old.get("sha256") == entry["sha256"]
                and int(old.get("bytes", -1)) == int(entry["bytes"])
            ):
                skipped.append(rel)
            else:
                uploads.append((rel, store_root / rel))
    uploads.sort(key=lambda item: item[0])
    skipped.sort()
    return uploads, skipped


def plan_publish_operations(
    store_root: Path,
    local_sources: dict[str, Any],
    remote_manifest: dict[str, Any] | None,
    *,
    remote_files: list[str] | None = None,
    prune_legacy: bool = False,
    force: bool = False,
    updated_at: str | None = None,
) -> PublishPlan:
    """Validate sanity gates and compute the exact upload/delete set for HF commit."""
    if not local_sources:
        raise ValueError(f"no Layer-1 Parquet files found in {store_root}")

    if (
        remote_manifest is not None
        and remote_manifest.get("schema_version") != mirror.MANIFEST_SCHEMA_VERSION
        and not prune_legacy
    ):
        raise mirror.MirrorError(
            f"remote mirror manifest has schema_version={remote_manifest.get('schema_version')!r}; "
            "pass --prune-legacy to replace legacy v1 data with v2"
        )

    baseline = None if prune_legacy else remote_manifest
    violations = mirror.check_sanity_gate(local_sources, baseline)
    if violations and not force:
        details = "\n  - ".join(violations)
        raise SanityGateError(f"sanity gate failed (pass --force to override):\n  - {details}")

    remote_entries = _remote_entry_map(baseline)
    uploads, skipped = _diff_local_uploads(store_root, local_sources, remote_entries)
    merged = mirror.merge_mirror_manifest(
        remote_manifest,
        local_sources,
        updated_at=updated_at,
        reset=prune_legacy,
    )

    deletes: list[str] = []
    if prune_legacy and remote_files:
        keep = _PRESERVED_ROOT_FILES | _manifest_paths(merged)
        deletes = sorted(f for f in remote_files if f not in keep and not f.startswith("."))

    return PublishPlan(
        uploads=tuple(uploads),
        skipped=tuple(skipped),
        deletes=tuple(deletes),
        merged_manifest=merged,
        write_readme=prune_legacy or remote_manifest is None,
    )


def fetch_remote_state(
    api: Any,
    repo_id: str,
) -> tuple[str | None, dict[str, Any] | None, list[str]]:
    """Fetch remote repo HEAD sha, ``manifest.json`` (if present), and file listing."""
    info = api.repo_info(repo_id=repo_id, repo_type="dataset")
    parent_commit: str | None = getattr(info, "sha", None)
    remote_files: list[str] = list(
        api.list_repo_files(repo_id=repo_id, repo_type="dataset", revision=parent_commit)
    )
    if "manifest.json" not in remote_files:
        return parent_commit, None, remote_files
    local_manifest = Path(
        api.hf_hub_download(
            repo_id=repo_id,
            filename="manifest.json",
            repo_type="dataset",
            revision=parent_commit,
        )
    )
    remote_manifest = json.loads(local_manifest.read_text(encoding="utf-8"))
    return parent_commit, remote_manifest, remote_files


def _emit_github_output(key: str, value: str) -> None:
    out_path = os.environ.get("GITHUB_OUTPUT")
    if not out_path:
        return
    with Path(out_path).open("a", encoding="utf-8") as handle:
        handle.write(f"{key}={value}\n")


def _build_commit_operations(
    plan: PublishPlan,
    *,
    add_cls: Any,
    delete_cls: Any,
) -> list[Any]:
    ops: list[Any] = [
        add_cls(path_in_repo=rel, path_or_fileobj=str(local_path))
        for rel, local_path in plan.uploads
    ]
    manifest_bytes = (json.dumps(plan.merged_manifest, indent=2, sort_keys=True) + "\n").encode(
        "utf-8"
    )
    ops.append(add_cls(path_in_repo="manifest.json", path_or_fileobj=manifest_bytes))
    if plan.write_readme:
        ops.append(
            add_cls(path_in_repo="README.md", path_or_fileobj=_DATASET_README.encode("utf-8"))
        )
    ops.extend(delete_cls(path_in_repo=rel) for rel in plan.deletes)
    return ops


def publish_store(
    *,
    data_dir: str | Path | None = None,
    repo_id: str | None = None,
    selected_sources: list[str] | None = None,
    dry_run: bool = False,
    force: bool = False,
    prune_legacy: bool = False,
    tag: str | None = None,
    message: str | None = None,
    api: Any | None = None,
    operation_classes: tuple[Any, Any] | None = None,
) -> PublishResult:
    """Scan local Layer-1 store, verify sanity gates, and atomically commit to Hugging Face."""
    target_repo = mirror.resolve_mirror(repo_id)
    store_root = store.store_dir(data_dir)
    src_filter = set(selected_sources) if selected_sources else None
    local_sources = scan_local_store(store_root, source_filter=src_filter)

    if api is None:
        hub = _load_hf_hub()
        token = os.environ.get("HF_TOKEN") or None
        api = hub.HfApi(token=token)
        add_cls = hub.CommitOperationAdd
        delete_cls = hub.CommitOperationDelete
    else:
        if operation_classes is not None:
            add_cls, delete_cls = operation_classes
        else:
            hub = _load_hf_hub()
            add_cls, delete_cls = hub.CommitOperationAdd, hub.CommitOperationDelete

    parent_commit, remote_manifest, remote_files = fetch_remote_state(api, target_repo)
    plan = plan_publish_operations(
        store_root,
        local_sources,
        remote_manifest,
        remote_files=remote_files,
        prune_legacy=prune_legacy,
        force=force,
    )

    if not plan.changed:
        _emit_github_output("changed", "false")
        return PublishResult(
            repo_id=target_repo,
            changed=False,
            uploaded=0,
            skipped=len(plan.skipped),
            deleted=0,
            dry_run=dry_run,
        )

    if dry_run:
        _emit_github_output("changed", "false")
        return PublishResult(
            repo_id=target_repo,
            changed=True,
            uploaded=len(plan.uploads),
            skipped=len(plan.skipped),
            deleted=len(plan.deletes),
            dry_run=True,
        )

    ops = _build_commit_operations(plan, add_cls=add_cls, delete_cls=delete_cls)
    src_list = ", ".join(sorted(local_sources))
    commit_msg = message or f"Update ogprod v2 mirror ({src_list})"
    commit_info = api.create_commit(
        repo_id=target_repo,
        repo_type="dataset",
        operations=ops,
        commit_message=commit_msg,
        parent_commit=parent_commit,
    )
    if tag:
        api.create_tag(repo_id=target_repo, repo_type="dataset", tag=tag, exist_ok=True)
    _emit_github_output("changed", "true")
    return PublishResult(
        repo_id=target_repo,
        changed=True,
        uploaded=len(plan.uploads),
        skipped=len(plan.skipped),
        deleted=len(plan.deletes),
        commit_url=getattr(commit_info, "commit_url", None),
        dry_run=False,
    )


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Publish ogprod v2 store to Hugging Face mirror.")
    parser.add_argument("--data-dir", type=Path, default=None, help="Local ogprod data directory.")
    parser.add_argument("--repo", default=None, help="HF dataset repo (default: $OGPROD_MIRROR).")
    parser.add_argument(
        "--sources",
        default=None,
        help="Comma-separated subset of sources to publish (default: all local sources).",
    )
    parser.add_argument("--dry-run", action="store_true", help="Plan publish without committing.")
    parser.add_argument("--force", action="store_true", help="Override sanity-gate failures.")
    parser.add_argument(
        "--prune-legacy",
        action="store_true",
        help="Reset remote manifest to v2 and delete legacy/unreferenced remote files.",
    )
    parser.add_argument("--tag", default=None, help="Optional git tag to create on HF after push.")
    parser.add_argument("--message", default=None, help="Custom HF commit message.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    selected = [s.strip() for s in args.sources.split(",") if s.strip()] if args.sources else None
    result = publish_store(
        data_dir=args.data_dir,
        repo_id=args.repo,
        selected_sources=selected,
        dry_run=args.dry_run,
        force=args.force,
        prune_legacy=args.prune_legacy,
        tag=args.tag,
        message=args.message,
    )
    mode = " [dry-run]" if result.dry_run else ""
    print(
        f"publish{mode} {result.repo_id}: changed={result.changed} "
        f"uploaded={result.uploaded} skipped={result.skipped} deleted={result.deleted}"
    )
    if result.commit_url:
        print(f"commit: {result.commit_url}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
